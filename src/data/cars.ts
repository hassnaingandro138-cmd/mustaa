export function formatPrice(price: number): string {
  return new Intl.NumberFormat('en-US', {
    style: 'currency',
    currency: 'USD',
    maximumFractionDigits: 0,
  }).format(price);
}

export function formatMileage(miles: number): string {
  return `${new Intl.NumberFormat('en-US').format(miles)} mi`;
}

export function getWhatsAppUrl(car?: Car, customMessage?: string): string {
  const text = customMessage
    ? customMessage
    : car
    ? `Hello MUSTAFA'S CARS, I am interested in the ${car.year} ${car.name} (${formatPrice(car.price)}, Stock #${car.specs.stockNumber}). Please share availability and viewing details.`
    : `Hello MUSTAFA'S CARS, I would like to speak with a showroom specialist regarding your vehicle collection.`;
  return `https://wa.me/${sanitizeWhatsAppNumber(BUSINESS_WHATSAPP_NUMBER)}?text=${encodeURIComponent(text)}`;
}
